import XCTest
@testable import RimeEngine
import CoreGraphics

/// S3 §7 asks for golden snapshots of the keyboard. Pixels need a device and a running app; the **model**
/// every view renders from does not, and it is what a refactor breaks silently. This snapshot therefore
/// fixes, for every layer and shift state at two widths, the numbers and strings the views draw: the
/// keyboard size, the candidate slot, every row and key frame, each key's kind and label, its
/// accessibility label, and the action-key state that rides along with it.
///
/// Running with `ARKEY_UPDATE_GOLDEN=1` rewrites the fixture; the diff it prints otherwise names the first
/// line that moved, so a failure says what changed rather than dumping two walls of text.
final class S3GoldenTests: XCTestCase {
  private var goldenURL: URL {
    URL(fileURLWithPath: #filePath)
      .deletingLastPathComponent()
      .deletingLastPathComponent()
      .appendingPathComponent("Golden", isDirectory: true)
      .appendingPathComponent("KeyboardLayout.txt")
  }

  private func snapshot() -> String {
    var lines = ["# The keyboard model, layer by layer. Generated by S3GoldenTests; update with",
                 "# ARKEY_UPDATE_GOLDEN=1 swift test --filter S3GoldenTests.",
                 "#",
                 "# width layer shift size candidate-slot globe return-label return-enabled",
                 "#   row index frame",
                 "#     kind label frame accessibility-label"]
    for width in [CGFloat(430), CGFloat(320)] {
      for layer in RimeKeyboardLayer.allCases {
        for shift in RimeShiftState.allCases {
          let layout = RimeKeyboardLayoutEngine.layout(
            width: width,
            layer: layer,
            shift: shift,
            returnKey: RimeReturnKey(label: "搜索", isEnabled: true),
            language: RimeLanguageKey(label: "中文", isASCII: false),
            needsGlobeRow: true)
          lines.append("width " + number(width)
                       + " layer " + layer.rawValue
                       + " shift " + shift.rawValue
                       + " size " + number(layout.size.width) + "x" + number(layout.size.height)
                       + " candidate " + rect(layout.candidateSlot)
                       + " globe " + String(layout.needsGlobeRow)
                       + " return " + layout.returnKey.label
                       + " enabled " + String(layout.returnKey.isEnabled))
          for (index, row) in layout.rows.enumerated() {
            lines.append("  row " + String(index) + " " + rect(row.frame))
            for key in row.keys {
              lines.append("    " + kind(key.kind) + " " + key.label + " " + rect(key.frame)
                           + " " + key.accessibilityLabel)
            }
          }
        }
      }
    }
    // S3 §7's remaining cells that are inputs to the layout model rather than pixels: the globe row
    // present or absent, the language key present or absent, every action-key label in both of its
    // states, and a keyboard with no candidate slot at all. Appearance is not here because the geometry
    // is identical in light and dark — the palette is pinned by S3AppearanceTests and the renders.
    lines.append("")
    lines.append("# Variants: the action key's labels and states, the globe and language keys, no slot.")
    for action in RimeReturnKey.Kind.allCases {
      for enabled in [true, false] {
        for globe in [true, false] {
          let layout = RimeKeyboardLayoutEngine.layout(
            width: 430,
            layer: .letters,
            returnKey: RimeReturnKey(label: action.label, isEnabled: enabled),
            language: RimeLanguageKey(label: "中文", isASCII: false),
            needsGlobeRow: globe)
          lines.append("variant return " + action.rawValue + " enabled " + String(enabled)
                       + " globe " + String(globe)
                       + " size " + number(layout.size.width) + "x" + number(layout.size.height)
                       + " candidate " + rect(layout.candidateSlot))
          // The two rows that can change: the action row, and the globe row when it exists.
          for row in layout.rows.suffix(2) {
            lines.append("  row " + rect(row.frame))
            for key in row.keys {
              lines.append("    " + kind(key.kind) + " " + key.label + " " + rect(key.frame)
                           + " " + key.accessibilityLabel)
            }
          }
        }
      }
    }

    let noLanguage = RimeKeyboardLayoutEngine.layout(width: 430, layer: .letters)
    lines.append("variant no-language size " + number(noLanguage.size.width) + "x"
                 + number(noLanguage.size.height) + " candidate " + rect(noLanguage.candidateSlot))
    for key in noLanguage.rows.last?.keys ?? [] {
      lines.append("  " + kind(key.kind) + " " + key.label + " " + rect(key.frame)
                   + " " + key.accessibilityLabel)
    }

    var bare = RimeKeyboardStyle.measured
    bare.candidateSlotHeight = 0
    let noSlot = RimeKeyboardLayoutEngine.layout(width: 430, layer: .letters, needsGlobeRow: true,
                                                 style: bare)
    lines.append("variant no-candidate-slot size " + number(noSlot.size.width) + "x"
                 + number(noSlot.size.height) + " candidate " + rect(noSlot.candidateSlot))
    for row in noSlot.rows.suffix(2) {
      lines.append("  row " + rect(row.frame))
      for key in row.keys {
        lines.append("    " + kind(key.kind) + " " + key.label + " " + rect(key.frame)
                     + " " + key.accessibilityLabel)
      }
    }
    return lines.joined(separator: "\n") + "\n"
  }

  private func kind(_ kind: RimeKeyboardKey.Kind) -> String {
    switch kind {
    case .character(let text): return "character(" + text + ")"
    case .shift(let state): return "shift(" + state.rawValue + ")"
    case .delete: return "delete"
    case .layer(let layer): return "layer(" + layer.rawValue + ")"
    case .emoji: return "emoji"
    case .language(let key): return "language(" + key.label + "," + String(key.isASCII) + ")"
    case .space: return "space"
    case .returnKey: return "return"
    case .globe: return "globe"
    }
  }

  private func rect(_ rect: CGRect) -> String {
    number(rect.minX) + "," + number(rect.minY) + " " + number(rect.width) + "x" + number(rect.height)
  }

  private func number(_ value: CGFloat) -> String { String(format: "%.1f", Double(value)) }

  func testTheKeyboardModelMatchesItsGoldenSnapshot() throws {
    let snapshot = self.snapshot()
    if ProcessInfo.processInfo.environment["ARKEY_UPDATE_GOLDEN"] == "1" {
      try FileManager.default.createDirectory(at: goldenURL.deletingLastPathComponent(),
                                              withIntermediateDirectories: true)
      try snapshot.write(to: goldenURL, atomically: true, encoding: .utf8)
      return
    }

    let golden = try String(contentsOf: goldenURL, encoding: .utf8)
    let expected = golden.split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
    let actual = snapshot.split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
    for index in 0..<max(expected.count, actual.count) {
      let was = index < expected.count ? expected[index] : "(missing)"
      let now = index < actual.count ? actual[index] : "(missing)"
      if was != now {
        return XCTFail("the model drifted from the golden snapshot at line " + String(index + 1)
                       + ":\n  golden: " + was + "\n  now:    " + now)
      }
    }
  }
}
